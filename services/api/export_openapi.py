"""Export contracts/openapi.yaml from the FastAPI app.

uv run python -m services.api.export_openapi          # write
uv run python -m services.api.export_openapi --check  # exit 1 if out of date
"""

import argparse
import sys
from pathlib import Path
from typing import Any

import yaml

from services.api.main import create_app

OPENAPI_PATH = Path(__file__).resolve().parents[2] / "contracts" / "openapi.yaml"

_HEADER = "# GENERATED by `make contract` (services/api/export_openapi.py). Do not edit by hand.\n"


def build_spec() -> dict[str, Any]:
    return create_app().openapi()


def render(spec: dict[str, Any]) -> str:
    return _HEADER + yaml.safe_dump(spec, sort_keys=False, allow_unicode=True, width=100)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the file is stale")
    args = parser.parse_args(argv)

    text = render(build_spec())
    if args.check:
        current = OPENAPI_PATH.read_text(encoding="utf-8") if OPENAPI_PATH.exists() else ""
        if current != text:
            print(f"{OPENAPI_PATH} is out of date; run `make contract`", file=sys.stderr)
            return 1
        return 0
    OPENAPI_PATH.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OPENAPI_PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
